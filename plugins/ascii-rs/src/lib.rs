use extism_pdk::*;
use serde::Deserialize;

#[derive(Deserialize)]
struct BannerInput {
    text: String,
    #[serde(default = "default_font")]
    font: String,
}

fn default_font() -> String { "standard".to_string() }

// Built-in FIGlet fonts (embedded so no filesystem access needed)
fn get_font_map(name: &str) -> &[(&str, &[&str])] {
    match name {
        "big" => &BIG_FONT,
        "block" => &BLOCK_FONT,
        "shadow" => &SHADOW_FONT,
        "slant" => &SLANT_FONT,
        _ => &STANDARD_FONT,
    }
}

fn get_font_height(name: &str) -> usize {
    match name {
        "big" => 8,
        "block" => 7,
        "shadow" => 7,
        "slant" => 6,
        _ => 6,
    }
}

#[plugin_fn]
pub fn banner(input: String) -> FnResult<String> {
    let input = match serde_json::from_str::<String>(&input) {
        Ok(s) => s,
        Err(_) => input,
    };

    let params: BannerInput = match serde_json::from_str(&input) {
        Ok(p) => p,
        Err(_) => BannerInput { text: input, font: default_font() },
    };

    let font_map = get_font_map(&params.font);
    let height = get_font_height(&params.font);
    let mut lines = vec![String::new(); height];

    for ch in params.text.chars() {
        let key = if ch.is_ascii() { ch.to_string() } else { "?".to_string() };
        let glyph = font_map.iter()
            .find(|(k, _)| *k == key.as_str())
            .or_else(|| font_map.iter().find(|(k, _)| *k == " "))
            .map(|(_, v)| *v);

        if let Some(rows) = glyph {
            for (i, line) in lines.iter_mut().enumerate() {
                if i < rows.len() {
                    line.push_str(rows[i]);
                }
            }
        }
    }

    // Trim trailing empty lines
    while lines.last().map_or(false, |l| l.trim().is_empty()) {
        lines.pop();
    }

    Ok(lines.join("\n"))
}

#[plugin_fn]
pub fn fonts(_input: String) -> FnResult<String> {
    let fonts = serde_json::json!(["standard", "big", "block", "shadow", "slant"]);
    Ok(fonts.to_string())
}

